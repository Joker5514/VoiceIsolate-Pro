#!/usr/bin/env node
/**
 * Generates the Landing "hero sculpture" (Signal Glass concept L2) as static
 * SVG and writes it into public/index.html between the hero-sculpture markers.
 *
 * The output is the prerendered still: it is what reduced-motion, Save-Data,
 * 2G, offline and CONSTRAINED-tier visitors see, and what every visitor sees
 * before landing-v3.js adds the 12 s drift. The cyan key (upper left) and gold
 * rim (back right) light washes are CSS on the stage so they can outgrow the frame. Geometry is the 1920 x 1200 frame
 * from the Signal Glass spec: the mixed recording enters at (0, 930) as a
 * cyan + gold double helix, passes a glass lens spanning x 990-1240, and exits
 * right as two single ribbons (Clean Voice at y 300, Background at y 690).
 *
 * Deterministic: the same source always writes the same bytes.
 *   node scripts/generate-hero-sculpture.mjs          # rewrite index.html
 *   node scripts/generate-hero-sculpture.mjs --check  # exit 1 if stale
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const INDEX = path.join(ROOT, 'public', 'index.html');
const START = '<!-- hero-sculpture:start (generated by scripts/generate-hero-sculpture.mjs) -->';
const END = '<!-- hero-sculpture:end -->';

const VOICE = '#22d3ee';
const BGST = '#f5b942';
const REF = '#c3cbd5';

const r1 = (v) => Math.round(v * 10) / 10;
const pt = ([x, y]) => `${Math.round(x)} ${Math.round(y)}`;

function cubic(p0, p1, p2, p3, t) {
  const u = 1 - t;
  const a = u * u * u, b = 3 * u * u * t, c = 3 * u * t * t, d = t * t * t;
  return [a * p0[0] + b * p1[0] + c * p2[0] + d * p3[0], a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1]];
}

/** Sample a cubic into `n` points with unit normals and arc-length fraction. */
function sampleCurve(p0, p1, p2, p3, n) {
  const pts = [];
  for (let i = 0; i <= n; i++) pts.push(cubic(p0, p1, p2, p3, i / n));
  let len = 0;
  const acc = [0];
  for (let i = 1; i < pts.length; i++) {
    len += Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]);
    acc.push(len);
  }
  return pts.map((p, i) => {
    const a = pts[Math.max(0, i - 1)], b = pts[Math.min(pts.length - 1, i + 1)];
    const dx = b[0] - a[0], dy = b[1] - a[1], m = Math.hypot(dx, dy) || 1;
    return { p, n: [-dy / m, dx / m], s: acc[i] / len, t: i / n };
  });
}

const smooth = (e0, e1, x) => { const k = Math.min(1, Math.max(0, (x - e0) / (e1 - e0))); return k * k * (3 - 2 * k); };
const off = (c, d) => [c.p[0] + c.n[0] * d, c.p[1] + c.n[1] * d];
const line = (arr) => `M${arr.map(pt).join('L')}`;

/** Closed band around a sampled curve with half-width hw(sample). */
function band(samples, hw) {
  const top = samples.map((c) => off(c, hw(c)));
  const bot = samples.map((c) => off(c, -hw(c))).reverse();
  return `${line(top)}L${bot.map(pt).join('L')}Z`;
}

// ── Geometry on the 1920 x 1200 frame ───────────────────────────────────────
const LENS = { cx: 1115, cy: 510, rx: 100, ry: 205, rot: 16 };
const HUB = [LENS.cx, LENS.cy];

// The braid stays under the copy column (y >= 700 until x 900), then rises into the lens.
const helix = sampleCurve([-40, 935], [620, 990], [930, 800], HUB, 150);
const TURNS = 6.5;
const amp = (c) => 46 * (1 - smooth(0.8, 1, c.t)) * (1 - 0.3 * c.t);
const strand = (sign) => helix.map((c) => {
  const phi = 2 * Math.PI * TURNS * c.s;
  return { xy: off(c, sign * amp(c) * Math.sin(phi)), depth: sign * Math.cos(phi), t: c.t };
});
const strandA = strand(1); // cyan: continues as the Clean Voice ribbon
const strandB = strand(-1); // gold: continues as the Background ribbon

/** Sub-paths of a strand where it passes in front of the other. */
function frontPath(s) {
  let d = '', open = false;
  for (const v of s) {
    if (v.depth > -0.05) { d += `${open ? 'L' : 'M'}${pt(v.xy)}`; open = true; } else open = false;
  }
  return d;
}

const voice = sampleCurve(HUB, [1330, 470], [1610, 300], [1990, 296], 64);
const bg = sampleCurve(HUB, [1330, 560], [1610, 690], [1990, 692], 64);
const voiceHw = (c) => (1.5 + 15 * Math.pow(c.t, 0.85)) * (0.4 + 0.6 * Math.abs(Math.cos(Math.PI * (1.15 * c.t + 0.18))));
const bgHw = (c) => 1.5 + 13 * Math.pow(c.t, 0.85);

const xAt = (samples, x) => samples.reduce((best, c) => (Math.abs(c.p[0] - x) < Math.abs(best.p[0] - x) ? c : best));

// Leader-line targets. Tag anchors are the spec's text anchors on the frame.
const TAGS = [
  { id: 'ref', label: 'Original', x: 288, y: 792, target: xAt(helix, 360).p, from: [330, 834] },
  { id: 'voice', label: 'Clean Voice', x: 1464, y: 196, target: xAt(voice, 1540).p, from: [1540, 236] },
  { id: 'bg', label: 'Background', x: 1276, y: 700, target: xAt(bg, 1330).p, from: [1330, 700] },
];

// Seeded particles (mulberry32) so the still never changes between builds.
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = rng(5514);
const particles = [];
while (particles.length < 44) {
  const x = 940 + rand() * 980, y = 110 + rand() * 900;
  const near = rand() < 0.28; // out-of-focus bokeh
  const hue = y < 470 ? VOICE : y > 600 ? BGST : REF;
  particles.push({ x, y, r: near ? 7 + rand() * 9 : 0.9 + rand() * 1.8, near, hue, o: near ? 0.1 + rand() * 0.1 : 0.28 + rand() * 0.34 });
}

// ── SVG ─────────────────────────────────────────────────────────────────────
const i = (n) => ' '.repeat(n);
const lensT = `rotate(${LENS.rot} ${LENS.cx} ${LENS.cy})`;
const lensEl = (extra) => `<ellipse cx="${LENS.cx}" cy="${LENS.cy}" rx="${LENS.rx}" ry="${LENS.ry}" ${extra}/>`;
const arc = (a0, a1, dx = 0) => {
  const at = (a) => [LENS.cx + dx + LENS.rx * Math.cos(a), LENS.cy + LENS.ry * Math.sin(a)];
  return `M${pt(at(a0))}A${LENS.rx} ${LENS.ry} 0 0 1 ${pt(at(a1))}`;
};
const hatchVoice = voice.slice(3);
const bgLines = [-0.72, -0.36, 0, 0.36, 0.72].map((k) => line(bg.slice(2).map((c) => off(c, k * bgHw(c)))));

const art = [
  `<svg class="v3-sculpture__art" viewBox="0 0 1920 1200" preserveAspectRatio="xMidYMid slice" role="img" aria-labelledby="heroSculptureTitle">`,
  `${i(2)}<title id="heroSculptureTitle">The original recording, a braid of voice and background, passes through a glass lens and separates into a clean voice ribbon and a background ribbon.</title>`,
  `${i(2)}<defs>`,
  `${i(4)}<radialGradient id="hsGlass" cx="0.36" cy="0.3" r="0.8"><stop offset="0" stop-color="#1a2330" stop-opacity="0.42"/><stop offset="1" stop-color="#0a0e14" stop-opacity="0.66"/></radialGradient>`,
  `${i(4)}<linearGradient id="hsSheen" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#e8eef5" stop-opacity="0.11"/><stop offset="0.55" stop-color="#e8eef5" stop-opacity="0.02"/><stop offset="1" stop-color="${BGST}" stop-opacity="0.05"/></linearGradient>`,
  `${i(4)}<linearGradient id="hsEdge" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${VOICE}" stop-opacity="0.36"/><stop offset="1" stop-color="${BGST}" stop-opacity="0.30"/></linearGradient>`,
  `${i(4)}<linearGradient id="hsSheath" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="${REF}" stop-opacity="0.09"/><stop offset="1" stop-color="${REF}" stop-opacity="0.03"/></linearGradient>`,
  `${i(4)}<linearGradient id="hsVoiceFill" x1="${HUB[0]}" y1="0" x2="1920" y2="0" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="${VOICE}" stop-opacity="0.18"/><stop offset="1" stop-color="${VOICE}" stop-opacity="0.42"/></linearGradient>`,
  `${i(4)}<linearGradient id="hsFade" x1="0" y1="0" x2="1920" y2="0" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#fff" stop-opacity="0.35"/><stop offset="0.12" stop-color="#fff"/><stop offset="0.94" stop-color="#fff"/><stop offset="1" stop-color="#fff" stop-opacity="0.5"/></linearGradient>`,
  `${i(4)}<mask id="hsEdgeFade" maskUnits="userSpaceOnUse" x="0" y="0" width="1920" height="1200"><rect width="1920" height="1200" fill="url(#hsFade)"/></mask>`,
  `${i(4)}<filter id="hsBloom" x="-10%" y="-10%" width="120%" height="120%"><feGaussianBlur stdDeviation="7"/></filter>`,
  `${i(2)}</defs>`,
  `${i(2)}<g mask="url(#hsEdgeFade)" fill="none" stroke-linecap="round" stroke-linejoin="round">`,
  `${i(4)}<g class="v3-sculpture__bloom" filter="url(#hsBloom)" opacity="0.35">`,
  `${i(6)}<path d="${frontPath(strandA)}" stroke="${VOICE}" stroke-width="7"/>`,
  `${i(6)}<path d="${frontPath(strandB)}" stroke="${BGST}" stroke-width="6"/>`,
  `${i(6)}<path d="${line(voice.map((c) => c.p))}" stroke="${VOICE}" stroke-width="10"/>`,
  `${i(6)}<path d="${line(bg.map((c) => c.p))}" stroke="${BGST}" stroke-width="7"/>`,
  `${i(4)}</g>`,
  `${i(4)}<g class="v3-sculpture__braid">`,
  `${i(6)}<path d="${line(strandA.map((v) => v.xy))}" stroke="${VOICE}" stroke-width="2.2" stroke-opacity="0.38"/>`,
  `${i(6)}<path d="${line(strandB.map((v) => v.xy))}" stroke="${BGST}" stroke-width="2" stroke-opacity="0.34"/>`,
  `${i(6)}<path d="${band(helix, (c) => amp(c) + 10)}" fill="url(#hsSheath)" stroke="${REF}" stroke-opacity="0.16" stroke-width="1"/>`,
  `${i(6)}<path d="${frontPath(strandA)}" stroke="${VOICE}" stroke-width="3.6"/>`,
  `${i(6)}<path d="${frontPath(strandB)}" stroke="${BGST}" stroke-width="3.2"/>`,
  `${i(4)}</g>`,
  `${i(4)}<g class="v3-sculpture__ribbons">`,
  `${i(6)}<path d="${band(hatchVoice, voiceHw)}" fill="url(#hsVoiceFill)" stroke="${VOICE}" stroke-opacity="0.55" stroke-width="1"/>`,
  `${i(6)}<path d="${line(voice.map((c) => c.p))}" stroke="${VOICE}" stroke-width="3.4"/>`,
  `${i(6)}<path d="${band(bg.slice(2), bgHw)}" fill="${BGST}" fill-opacity="0.07"/>`,
  ...bgLines.map((d, k) => `${i(6)}<path d="${d}" stroke="${BGST}" stroke-width="${k === 2 ? 2.6 : 1}" stroke-opacity="${k === 2 ? 1 : 0.6}"/>`),
  `${i(4)}</g>`,
  `${i(2)}</g>`,
  `${i(2)}<g class="v3-sculpture__lens" transform="${lensT}">`,
  `${i(4)}${lensEl('fill="none" stroke="' + BGST + '" stroke-opacity="0.22" stroke-width="3" transform="translate(7 0)"')}`,
  `${i(4)}${lensEl('fill="url(#hsGlass)"')}`,
  `${i(4)}${lensEl('fill="url(#hsSheen)"')}`,
  `<ellipse cx="${LENS.cx}" cy="${LENS.cy}" rx="${LENS.rx - 7}" ry="${LENS.ry - 9}" fill="none" stroke="#e8eef5" stroke-opacity="0.08" stroke-width="1"/>`.replace(/^/, i(4)),
  `${i(4)}${lensEl('fill="none" stroke="url(#hsEdge)" stroke-width="2"')}`,
  `${i(4)}<path d="${arc(Math.PI * 1.05, Math.PI * 1.42)}" fill="none" stroke="#cff6fc" stroke-opacity="0.5" stroke-width="2" stroke-linecap="round"/>`,
  `${i(4)}<path d="${arc(Math.PI * 0.08, Math.PI * 0.4, 7)}" fill="none" stroke="${BGST}" stroke-opacity="0.45" stroke-width="2" stroke-linecap="round"/>`,
  `${i(2)}</g>`,
  `${i(2)}<g class="v3-sculpture__leaders" fill="none" stroke="#e8eef5" stroke-opacity="0.34" stroke-width="1">`,
  ...TAGS.map((t) => `${i(4)}<path d="M${pt(t.from)}L${pt(t.target)}"/><circle cx="${r1(t.target[0])}" cy="${r1(t.target[1])}" r="3" fill="#e8eef5" fill-opacity="0.8" stroke="none"/>`),
  `${i(2)}</g>`,
  `</svg>`,
];

const BOKEH = { [VOICE]: 'hsBokehVoice', [BGST]: 'hsBokehBg', [REF]: 'hsBokehRef' };
const dust = [
  `<svg class="v3-sculpture__dust" viewBox="0 0 1920 1200" preserveAspectRatio="xMidYMid slice" aria-hidden="true" focusable="false">`,
  `${i(2)}<defs>`,
  ...Object.entries(BOKEH).map(([hue, id]) => `${i(4)}<radialGradient id="${id}"><stop offset="0" stop-color="${hue}"/><stop offset="0.55" stop-color="${hue}" stop-opacity="0.45"/><stop offset="1" stop-color="${hue}" stop-opacity="0"/></radialGradient>`),
  `${i(2)}</defs>`,
  ...particles.map((p) => (p.near
    ? `${i(2)}<circle cx="${r1(p.x)}" cy="${r1(p.y)}" r="${r1(p.r)}" fill="url(#${BOKEH[p.hue]})" opacity="${Math.round(p.o * 100) / 100}"/>`
    : `${i(2)}<circle cx="${r1(p.x)}" cy="${r1(p.y)}" r="${r1(p.r)}" fill="${p.hue}" fill-opacity="${Math.round(p.o * 100) / 100}"/>`)),
  `</svg>`,
];

const tagIcon = {
  ref: '<span class="v3-tag__glyph" aria-hidden="true">Σ</span>',
  voice: '<svg class="v3-tag__glyph" viewBox="0 0 16 16" aria-hidden="true" focusable="false"><path d="M1 8h2l1.5-4 2 8 2-10 2 9 1.5-3H15" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"/></svg>',
  bg: '<svg class="v3-tag__glyph" viewBox="0 0 16 16" aria-hidden="true" focusable="false"><path d="M8 2 15 5.5 8 9 1 5.5Z M1 9l7 3.5L15 9" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linejoin="round"/></svg>',
};
const legend = [
  `<ul class="v3-legend" aria-label="What the picture shows">`,
  ...TAGS.map((t) => `${i(2)}<li class="v3-tag v3-tag--${t.id}" style="--tag-x:${r1((t.x / 1920) * 100)}%;--tag-y:${r1((t.y / 1200) * 100)}%">${tagIcon[t.id]}${t.label}</li>`),
  `</ul>`,
];

const indent = (lines, n) => lines.map((l) => i(n) + l).join('\n');
const block = [
  START,
  `<div class="v3-sculpture__frame">`,
  `${i(2)}<div class="v3-sculpture__layer v3-sculpture__layer--body">`,
  indent(art, 4),
  `${i(2)}</div>`,
  `${i(2)}<div class="v3-sculpture__layer v3-sculpture__layer--dust">`,
  indent(dust, 4),
  `${i(2)}</div>`,
  `</div>`,
  ...legend,
  END,
].map((l) => l.split('\n').map((s) => i(8) + s).join('\n')).join('\n');

const html = fs.readFileSync(INDEX, 'utf8');
const a = html.indexOf(START), b = html.indexOf(END);
if (a < 0 || b < a) {
  console.error('[VIP] hero-sculpture markers not found in public/index.html');
  process.exit(1);
}
const lineStart = html.lastIndexOf('\n', a) + 1;
const next = html.slice(0, lineStart) + block + html.slice(b + END.length);
if (process.argv.includes('--check')) {
  if (next !== html) { console.error('[VIP] public/index.html hero sculpture is stale; run node scripts/generate-hero-sculpture.mjs'); process.exit(1); }
  console.log('[VIP] hero sculpture up to date');
} else {
  fs.writeFileSync(INDEX, next);
  console.log(`[VIP] wrote hero sculpture (${block.length} bytes) to public/index.html`);
  const yAt = (x) => r1(xAt(helix, x).p[1]);
  console.log(`[VIP] helix centre y at x=600: ${yAt(600)}, x=900: ${yAt(900)}, x=990: ${yAt(990)}`);
}
